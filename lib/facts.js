const грн = n => Math.round(n).toLocaleString('uk-UA').replace(/ /g, ' ') + ' грн';
const тел = p => {
  const d = String(p || '').replace(/\D/g, '');
  const m = d.match(/^(?:38)?(0\d{2})(\d{3})(\d{2})(\d{2})$/);
  return m ? `+38 ${m[1]} ${m[2]} ${m[3]} ${m[4]}` : String(p || '');
};

function ціна(F, w, h) {
  const tiers = (Array.isArray(F.tiers) ? F.tiers : [])
    .map(t => ({ toH: Number(t.toH != null ? t.toH : t.toW) || 0, base: Number(t.base) || 0, perM: Number(t.perM) || 0 }))
    .sort((a, b) => a.toH - b.toH);
  if (!tiers.length) return null;
  if (h > tiers[tiers.length - 1].toH) return null;
  const t = tiers.find(x => h <= x.toH) || tiers[tiers.length - 1];
  const effW = Math.max(w, Number(F.fromW) || 0);
  return Math.round(t.base + t.perM * (effW / 100));
}

