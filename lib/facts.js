  const F = { ...ДЕФОЛТ.rollerFormula, ...(s.rollerFormula || {}) };
  const tiers = (Array.isArray(F.tiers) && F.tiers.length ? F.tiers : ДЕФОЛТ.rollerFormula.tiers);
  const formula = { ...F, tiers };
